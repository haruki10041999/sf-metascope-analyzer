/** 小文字化した名前空間名から、資料の表記を参照する。 */
export const APEX_STANDARD_NAMESPACES: ReadonlyMap<string, string> = new Map(
    Object.keys(STANDARD_TYPES_BY_NAMESPACE).map((name) => [name.toLowerCase(), name]),
);

/** 小文字化した完全修飾名から、資料に掲載された標準型を参照する。 */
export const APEX_STANDARD_TYPES: ReadonlyMap<string, ApexStandardType> = new Map(
    Object.entries(STANDARD_TYPES_BY_NAMESPACE).flatMap(([namespace, entries]) =>
        entries.map(([name, kind, status]): [string, ApexStandardType] => {
            const qualifiedName = `${namespace}.${name}`;
            const methodExamples = METHOD_EXAMPLES[qualifiedName];
            return [
                qualifiedName.toLowerCase(),
                {
                    qualifiedName,
                    namespace,
                    kinds: typeof kind === 'string' ? [kind] : kind,
                    ...(status !== undefined && { status }),
                    ...(methodExamples !== undefined && { methodExamples }),
                },
            ];
        }),
    ),
);

export const findApexStandardNamespace = (name: string): string | undefined =>
    APEX_STANDARD_NAMESPACES.get(name.toLowerCase());

/** 完全修飾名を照合する。未収録の型は undefined を返す。 */
export const findApexStandardType = (qualifiedName: string): ApexStandardType | undefined =>
    APEX_STANDARD_TYPES.get(qualifiedName.toLowerCase());
