export type ApexStandardTypeKind = 'class' | 'interface' | 'enum' | 'exception' | 'unknown';
export type ApexStandardTypeStatus = 'retired' | 'pilot' | 'developerPreview';

export type ApexStandardType = {
    readonly qualifiedName: string;
    readonly namespace: string;
    /** 資料に複数の種別が記載されている場合はすべて保持する。 */
    readonly kinds: readonly ApexStandardTypeKind[];
    readonly status?: ApexStandardTypeStatus;
    /** 資料で確認されたメソッド名の例。 */
    readonly methodExamples?: readonly string[];
};

type StandardTypeEntry = readonly [
    name: string,
    kind: ApexStandardTypeKind | readonly ApexStandardTypeKind[],
    status?: ApexStandardTypeStatus,
];

